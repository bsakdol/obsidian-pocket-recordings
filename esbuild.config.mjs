import esbuild from "esbuild";
import process from "process";
import { copyFileSync, existsSync, mkdirSync } from "node:fs";
import { builtinModules } from "node:module";
import { join } from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// When OBSIDIAN_VAULT names a test vault (set it in a git-ignored .env), every build also copies the
// plugin into that vault. Copying rather than symlinking works for vaults synced by iCloud or
// Obsidian Sync, which carry real files to other devices but not symlinks.
const vault = process.env.OBSIDIAN_VAULT?.trim();
const installToVault = {
	name: "install-to-vault",
	setup(build) {
		build.onEnd((result) => {
			if (!vault || result.errors.length > 0) return;
			if (!existsSync(join(vault, ".obsidian"))) {
				console.error(`OBSIDIAN_VAULT is not an Obsidian vault: ${vault}`);
				return;
			}
			const dir = join(vault, ".obsidian", "plugins", "pocket-recordings");
			mkdirSync(dir, { recursive: true });
			for (const file of ["main.js", "manifest.json", "styles.css"]) {
				if (existsSync(file)) copyFileSync(file, join(dir, file));
			}
			console.log(`Installed into ${dir}`);
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [installToVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
